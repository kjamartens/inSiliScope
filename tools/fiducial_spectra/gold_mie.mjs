#!/usr/bin/env node
// Scattering and absorption cross sections of gold spheres in water (Mie theory, Bohren & Huffman's BHMIE, bohren1983)
// from Johnson & Christy's optical constants (data/fiducials/gold_johnson_christy.json, n and k linear in wavelength
// between their points). Writes data/fiducials/gold_mie.json: sigma_sca and sigma_abs (um^2) on a wavelength x
// diameter grid; the engine interpolates bilinearly. Self-checks: the small-sphere limit against the dipole (Rayleigh)
// formulas, and Q_ext = Q_sca + Q_abs.
//   node tools/fiducial_spectra/gold_mie.mjs [--check]
// BSD-3-Clause.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, formatJson } from './curves.mjs';

const N_MEDIUM = 1.333;  // water (the beads' buffer)
const LAMBDA = { minNm: 400, maxNm: 900, stepNm: 10 }, DIAM = { minNm: 20, maxNm: 400, stepNm: 10 };
const OUT = path.join(ROOT, 'data', 'fiducials', 'gold_mie.json');
const jc = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'fiducials', 'gold_johnson_christy.json'), 'utf8')).nk;

function goldIndex(nm) {
  let k = 0;
  while (k < jc.length - 2 && jc[k + 1][0] < nm) ++k;
  const [a, na, ka] = jc[k], [b, nb, kb] = jc[k + 1], f = (nm - a) / (b - a);
  return [na + (nb - na) * f, ka + (kb - ka) * f];
}

// Complex arithmetic on [re, im].
const add = (a, b) => [a[0] + b[0], a[1] + b[1]], sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const mul = (a, b) => [a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0]];
const div = (a, b) => { const d = b[0] * b[0] + b[1] * b[1]; return [(a[0] * b[0] + a[1] * b[1]) / d, (a[1] * b[0] - a[0] * b[1]) / d]; };
const scale = (a, s) => [a[0] * s, a[1] * s];

// Efficiencies Q_ext, Q_sca of a sphere: size parameter x = 2 pi r n_medium / lambda, relative index m (BHMIE).
export function mie(x, m) {
  const y = mul(m, [x, 0]), nstop = Math.round(x + 4 * Math.cbrt(x) + 2);
  const nmx = Math.round(Math.max(nstop, Math.hypot(y[0], y[1])) + 15);
  const d = new Array(nmx + 1).fill([0, 0]);  // logarithmic derivative D_n(mx), downward recurrence
  for (let n = nmx; n >= 1; --n) { const nf = div([n, 0], y); d[n - 1] = sub(nf, div([1, 0], add(d[n], nf))); }
  let psi0 = Math.cos(x), psi1 = Math.sin(x), chi0 = -Math.sin(x), chi1 = Math.cos(x);
  let qsca = 0, qext = 0;
  for (let n = 1; n <= nstop; ++n) {
    const psi = (2 * n - 1) * psi1 / x - psi0, chi = (2 * n - 1) * chi1 / x - chi0;
    const xi = [psi, -chi], xi1 = [psi1, -chi1];
    const da = add(div(d[n], m), [n / x, 0]), db = add(mul(d[n], m), [n / x, 0]);
    const an = div(sub(scale(da, psi), [psi1, 0]), sub(mul(da, xi), xi1));
    const bn = div(sub(scale(db, psi), [psi1, 0]), sub(mul(db, xi), xi1));
    qsca += (2 * n + 1) * (an[0] ** 2 + an[1] ** 2 + bn[0] ** 2 + bn[1] ** 2);
    qext += (2 * n + 1) * (an[0] + bn[0]);
    psi0 = psi1; psi1 = psi; chi0 = chi1; chi1 = chi;
  }
  return { qext: 2 * qext / (x * x), qsca: 2 * qsca / (x * x) };
}

function cross(nm, dNm) {
  const [n, k] = goldIndex(nm), m = [n / N_MEDIUM, k / N_MEDIUM], r = dNm / 2e3;  // um
  const x = 2 * Math.PI * (dNm / 2) * N_MEDIUM / nm, area = Math.PI * r * r, q = mie(x, m);
  return { sca: q.qsca * area, abs: (q.qext - q.qsca) * area };
}

// Self-checks: a 5 nm sphere against the dipole formulas (Bohren & Huffman eq. 5.8, 5.11: Q_sca = 8/3 x^4 |(m^2-1)/(m^2+2)|^2,
// Q_abs = 4 x Im((m^2-1)/(m^2+2))), and a lossless sphere's Q_ext = Q_sca.
{
  const [n, k] = goldIndex(530), m = [n / N_MEDIUM, k / N_MEDIUM], x = 2 * Math.PI * 2.5 * N_MEDIUM / 530;
  const m2 = mul(m, m), pol = div(sub(m2, [1, 0]), add(m2, [2, 0])), q = mie(x, m);
  const qs = 8 / 3 * x ** 4 * (pol[0] ** 2 + pol[1] ** 2), qa = 4 * x * pol[1];
  if (Math.abs(q.qsca / qs - 1) > 0.02 || Math.abs((q.qext - q.qsca) / qa - 1) > 0.02)
    throw new Error(`Mie vs dipole limit: Q_sca ${q.qsca} vs ${qs}, Q_abs ${q.qext - q.qsca} vs ${qa}`);
  const g = mie(3, [1.2, 0]);
  if (Math.abs(g.qext - g.qsca) > 1e-9) throw new Error(`lossless sphere: Q_ext ${g.qext} != Q_sca ${g.qsca}`);
}

const lambdas = [], diams = [];
for (let l = LAMBDA.minNm; l <= LAMBDA.maxNm; l += LAMBDA.stepNm) lambdas.push(l);
for (let d = DIAM.minNm; d <= DIAM.maxNm; d += DIAM.stepNm) diams.push(d);
const p4 = v => Number(v.toPrecision(4));
const table = diams.map(d => lambdas.map(l => cross(l, d)));
const out = {
  about: `Gold spheres in water (n ${N_MEDIUM}): Mie scattering and absorption cross sections, um^2, per diameter (rows, `
    + `diameterNm) and wavelength (columns, lambdaNm). Generated by tools/fiducial_spectra/gold_mie.mjs (Bohren & Huffman's `
    + `BHMIE, bohren1983) from Johnson & Christy's optical constants (johnson1972); do not edit by hand.`,
  refs: ['bohren1983', 'johnson1972', 'polyanskiy2024'],
  mediumIndex: N_MEDIUM,
  lambdaNm: LAMBDA, diameterNm: DIAM,
  scatteringUm2: table.map(row => row.map(c => p4(c.sca))),
  absorptionUm2: table.map(row => row.map(c => p4(c.abs))),
};
const text = formatJson(out);
if (process.argv.includes('--check')) {
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  if (old !== text) { console.error('data/fiducials/gold_mie.json is stale: run node tools/fiducial_spectra/gold_mie.mjs'); process.exit(1); }
} else {
  fs.writeFileSync(OUT, text);
  console.log('wrote data/fiducials/gold_mie.json');
}
for (const d of [40, 80, 100, 150, 200]) {
  const c = diams.indexOf(d), row = table[c];
  let best = 0;
  row.forEach((v, i) => { if (v.sca + v.abs > row[best].sca + row[best].abs) best = i; });
  console.log(`${d} nm: extinction peak ${lambdas[best]} nm, sigma_sca ${row[best].sca.toPrecision(3)} um^2, sigma_abs ${row[best].abs.toPrecision(3)} um^2; at 561 nm sca ${cross(561, d).sca.toPrecision(3)}, abs ${cross(561, d).abs.toPrecision(3)}`);
}
