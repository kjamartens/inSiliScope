#!/usr/bin/env node
// SPDX-License-Identifier: BSD-3-Clause
// The viewer's design tokens (web/design/tokens/*.tokens.json, W3C Design Tokens Format Module 2025.10 structure) ->
// web/design/tokens.css (CSS custom properties, the runtime layer). Rules: docs/dev/DESIGN.md.
//
//   node tools/gen_design_tokens.mjs           write web/design/tokens.css
//   node tools/gen_design_tokens.mjs --check   fail when it is out of date (CI)
//
// A token's CSS name is its path joined by '-' with a last 'default' dropped (color.text.default -> --color-text,
// color.text.muted -> --color-text-muted). An alias {a.b} becomes var(--a-b), so the accent override (theme.js) and the
// themes act through the references. Layers: :root = primitives + accent + Dark + Comfortable; the Light theme under
// :root[data-theme=light] and, for "Follow system", under :root[data-theme=system] in a prefers-color-scheme: light
// query; Compact under :root[data-density=compact]; the Dark set again under .isc-dark (the image areas, dark in every
// theme).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TOKEN_DIR = path.join(ROOT, 'web/design/tokens');
const OUT = path.join(ROOT, 'web/design/tokens.css');

const read = f => JSON.parse(fs.readFileSync(path.join(TOKEN_DIR, f), 'utf8'));
export const cssName = p => '--' + (p[p.length - 1] === 'default' ? p.slice(0, -1) : p).join('-');

// every token of a file: [path array, $value, $type] (the type inherited from its group)
export function flatten(obj, p = [], type) {
  const out = [];
  if (obj && typeof obj === 'object' && '$value' in obj) return [[p, obj.$value, obj.$type || type]];
  for (const k of Object.keys(obj || {})) {
    if (k.startsWith('$')) continue;
    out.push(...flatten(obj[k], p.concat(k), obj.$type || type));
  }
  return out;
}

export function loadSets() {
  return {
    primitives: flatten(read('primitives.tokens.json')),
    accent: flatten(read('accent.tokens.json')),
    dark: flatten(read('semantic.dark.tokens.json')),
    light: flatten(read('semantic.light.tokens.json')),
    comfortable: flatten(read('density.comfortable.tokens.json')),
    compact: flatten(read('density.compact.tokens.json')),
  };
}

const ALIAS = /\{([^}]+)\}/g;
const cssValue = v => String(v).replace(ALIAS, (_, ref) => `var(${cssName(ref.split('.'))})`);

// The resolved literal of every CSS name in a theme (aliases followed), for the lint's contrast checks.
export function resolve(theme = 'dark', density = 'comfortable', accentOverride) {
  const S = loadSets(), map = new Map();
  const put = set => { for (const [p, v] of set) map.set(p.join('.'), v); };
  put(S.primitives); put(S.accent); put(S.dark); put(S.comfortable);
  if (theme === 'light') put(S.light);
  if (density === 'compact') put(S.compact);
  if (accentOverride) { map.set('accent.dark', accentOverride); map.set('accent.light', accentOverride); }
  const get = (key, depth = 0) => {
    if (depth > 20) throw new Error('alias loop at ' + key);
    if (!map.has(key)) throw new Error('unknown token ' + key);
    return String(map.get(key)).replace(ALIAS, (_, ref) => get(ref, depth + 1));
  };
  const out = {};
  for (const key of map.keys()) out[cssName(key.split('.'))] = get(key);
  return out;
}

export function generate() {
  const S = loadSets();
  // every alias must name a token
  resolve('dark'); resolve('light'); resolve('dark', 'compact');
  const block = (sel, sets, indent = '') => {
    const lines = [];
    for (const set of sets) for (const [p, v] of set) lines.push(`${indent}  ${cssName(p)}: ${cssValue(v)};`);
    return `${indent}${sel} {\n${lines.join('\n')}\n${indent}}\n`;
  };
  return '/* GENERATED by tools/gen_design_tokens.mjs from web/design/tokens/*.tokens.json: do not edit (docs/dev/DESIGN.md). */\n' +
    block(':root', [S.primitives, S.accent, S.dark, S.comfortable]) +
    ':root { color-scheme: dark; }\n' +
    block(':root[data-theme=light]', [S.light]) +
    ':root[data-theme=light] { color-scheme: light; }\n' +
    '@media (prefers-color-scheme: light) {\n' + block(':root[data-theme=system]', [S.light], '  ') +
    '  :root[data-theme=system] { color-scheme: light; }\n}\n' +
    block(':root[data-density=compact]', [S.compact]) +
    '/* the world view, the live image and their overlays: Dark in every theme */\n' +
    block('.isc-dark', [S.dark]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = generate();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== css) { console.error('web/design/tokens.css is out of date: run node tools/gen_design_tokens.mjs'); process.exit(1); }
    console.log('web/design/tokens.css is up to date');
  } else {
    fs.writeFileSync(OUT, css);
    console.log('wrote web/design/tokens.css');
  }
}
