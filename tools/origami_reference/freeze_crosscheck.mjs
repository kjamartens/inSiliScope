// Freezes the nanoruler model's cross-check against origami_bend.py (the model reference) into
// tests/parity/origami_bend_ref.inc, which world_checks.origami compares the C++ with: three molecules, each the
// reference's bent sites (x, y, height above the surface, nm) and end angle for the bending normals the JS/C++ draw
// for it (bendNormal), at three persistence lengths. Re-run after a deliberate change of the rod model.
//   node tools/origami_reference/freeze_crosscheck.mjs      (needs python with numpy)
// BSD-3-Clause.
import { execFileSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { ORIGAMI_DESIGNS, normalizeOrigamiParams, origamiGeometry, bendNormal } from '../../web/prototype/scope/origami.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const d = ORIGAMI_DESIGNS[0], G = origamiGeometry(d, normalizeOrigamiParams({ specimen: 1 }));
const POS = d.spots.map(s => s.u * G.s + G.L / 2);
const cases = [[11, 273.1], [12, 1500], [13, 100]].map(([h, Lp]) => {
  const n = Math.max(8, Math.ceil(G.L / d.segmentNm));
  return { h, Lp, normals: Array.from({ length: n }, (_, i) => bendNormal(h, i)), roll: 0.3 + h / 10, lengthNm: G.L,
    diameterNm: G.H, lpNm: Lp, segmentNm: d.segmentNm, positionsNm: POS, nAround: 5 };
});
const res = JSON.parse(execFileSync('python', ['-I', path.join(ROOT, 'tools/origami_reference/crosscheck.py')],
  { input: JSON.stringify({ cases }), encoding: 'utf8' })).results;
const num = v => String(v);   // shortest round trip: the C++ reads back the same double
const lines = ['// Generated by tools/origami_reference/freeze_crosscheck.mjs: origami_bend.py\'s bent sites for the JS/C++ bending',
  '// normals of three molecules (world_checks.origami). Do not edit.',
  '// { h1, Lp nm, roll rad, segments, end angle, { sites: x, y, height nm, ring k * 5 + n } }'];
cases.forEach((c, i) => {
  if (res[i].n !== c.normals.length) throw new Error(`case ${i}: ${res[i].n} segments vs ${c.normals.length} normals`);
  lines.push(`{ ${c.h}u, ${num(c.Lp)}, ${num(c.roll)}, ${res[i].n}, ${num(res[i].endAngle)}, {`);
  for (const s of res[i].sites) lines.push(`   ${s.map(num).join(', ')},`);
  lines.push('} },');
});
const out = path.join(ROOT, 'tests/parity/origami_bend_ref.inc');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${path.relative(ROOT, out)} (${cases.length} molecules, ${res[0].sites.length} sites each)`);
